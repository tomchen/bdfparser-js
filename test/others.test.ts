import { $Font, $Glyph, $Bitmap } from '../src/shortcuts'
import { unifont_path, glyph_a_meta, unifont_emptylines_path } from './info'
import { Font } from '../src/Font'
import { Glyph } from '../src/Glyph'
import { Bitmap } from '../src/Bitmap'
import readlineiter from 'readlineiter'
import { readFileSync } from 'fs'

describe('Shortcuts', () => {
  test('$Font creates and loads font correctly', async () => {
    const font = await $Font(readlineiter(unifont_path), {})
    expect(font).toBeInstanceOf(Font)
    expect(font.headers).toBeDefined()
    expect(font.glyphs.size).toBeGreaterThan(0)
  })

  test('$Font with encoding options works', async () => {
    const encodingOptions = {
      charset: 'utf8',
      char2cp: (_char: string) => 0,
      cp2char: (_cp: number) => 'a',
    }
    const font = await $Font(readlineiter(unifont_path), encodingOptions)
    expect(font.charset).toBe('utf8')
  })

  test('$Glyph creates glyph correctly', async () => {
    const font = await $Font(readlineiter(unifont_path), {})
    const glyph = $Glyph(glyph_a_meta, font)
    expect(glyph).toBeInstanceOf(Glyph)
    expect(glyph.meta).toEqual(glyph_a_meta)
  })

  test('$Bitmap creates bitmap correctly', () => {
    const bindata = ['11111111', '10000001', '10000001', '11111111']
    const bitmap = $Bitmap(bindata)
    expect(bitmap).toBeInstanceOf(Bitmap)
    expect(bitmap.bindata).toEqual(bindata)
    expect(bitmap.width()).toBe(8)
    expect(bitmap.height()).toBe(4)
  })
})

