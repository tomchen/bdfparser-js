describe('tobdf', () => {
  test('unifont tobdf()', async () => {
    const font = new Font()
    await font.load_filelines(readlineiter(unifont_path))
    expect(font.tobdf().trim()).toEqual(
      readFileSync(unifont_path, 'utf8').trim()
    )
  })
})
